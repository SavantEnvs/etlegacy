#!/usr/bin/env python3
"""Embed game data files into a C table for the game-module harness.

usage: embed_files.py <out.c> <root> <subdir>...
Every regular file under <root>/<subdir> becomes { "<subdir>/<path>", bytes, len }.
"""
import os
import sys


def main():
    out, root, subdirs = sys.argv[1], sys.argv[2], sys.argv[3:]
    files = []
    for sub in subdirs:
        for d, _, names in os.walk(os.path.join(root, sub)):
            for n in names:
                p = os.path.join(d, n)
                files.append((os.path.relpath(p, root).replace(os.sep, '/'), p))
    files.sort()
    with open(out + '.tmp', 'w') as f:
        f.write('/* generated by mayhem/tools/embed_files.py */\n')
        f.write('typedef struct { const char *name; const unsigned char *data; int len; } fz_file_t;\n')
        for i, (_, p) in enumerate(files):
            data = open(p, 'rb').read()
            f.write('static const unsigned char fz_f%d[] = {' % i)
            f.write(','.join(str(b) for b in data) or '0')
            f.write('};\n')
        f.write('const fz_file_t fz_files[] = {\n')
        for i, (name, p) in enumerate(files):
            f.write('\t{ "%s", fz_f%d, %d },\n' % (name, i, os.path.getsize(p)))
        f.write('};\nconst int fz_numfiles = %d;\n' % len(files))
    os.replace(out + '.tmp', out)


if __name__ == '__main__':
    main()
